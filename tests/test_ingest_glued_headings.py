# ---------------------------------------------------------------------------

_RECOVERY_KEEPS_DECORATION_TEXT = (
    "第一章 开端\n"
    "故事的开端平静而寻常，谁也没想到接下来会发生那么多出乎意料的事情，"
    "一切看起来都和往常没有什么不同，阳光照常升起，街道照常车水马龙。"
    "接下来的几个月里什么都没有发生，大家都渐渐放松了警惕，日子一天天过去，"
    "谁也没想到后面的转折会来得这样突然，一切都在悄无声息中悄然酝酿著。\n"
    "--- 第2章 中段 ---\n"
    "剧情在这一段陡然加快，几个关键人物相继登场，线索也渐渐浮出水面，"
    "读者能感觉到一场大戏即将拉开序幕，气氛一点一点变得紧张起来。\n"
    "--- 第2章 中段 ---\n"
    "另一边的视角也在同时推进，两条线渐渐有了交汇的迹象，仔细看就能发现"
    "其中埋藏的呼应与伏笔，故事的轮廓开始变得清晰，令人愈发期待后续。\n"
    "第三章 结局\n"
    "最终一切谜底揭晓，所有悬而未决的线索都有了交代，故事画上了圆满的"
    "句号，读者合上书页，心里却还回响著那些曾经牵动人心的片段与画面。\n"
)


def test_recovery_branch_keeps_original_decoration_in_body_first_line() -> None:
    """两条完全相同的 `--- 第2章 中段 ---` 紧邻出现，各自的紧邻候选序号都
    等于自己（同序号），被 ``_accept_inline_matches`` 判定不连续而拒收，
    退回给 ``app.ingest._recover_missing_unit_headings`` 的序号断点兜底：
    标题字段仍去装饰（干净），但核心前的前缀 `--- ` 不含任何字母（汉字同样
    算字母），是标题自身的装饰，不是上一章残片——正文首行必须保留原文整行
    `--- 第2章 中段 ---`（带装饰），不挪进上一章；这是为了幂等：若把 `---`
    挪去上一章，第二次切章会把正文里这行 `第2章 中段 ---` 当独占行标题重新
    识别出来，标题带上尾部的 `---`，同一篇文章切两次结果不同。
    """
    chapters = ingest_novel(_RECOVERY_KEEPS_DECORATION_TEXT.encode("utf-8"))["chapters"]

    assert [c["title"] for c in chapters] == ["第一章 开端", "第2章 中段", "第三章 结局"]
    assert chapters[0]["content"].endswith("悄然酝酿著。")
    assert chapters[1]["content"].startswith("--- 第2章 中段 ---")
    assert "剧情在这一段陡然加快" in chapters[1]["content"]
    assert "另一边的视角也在同时推进" in chapters[1]["content"]


# ---------------------------------------------------------------------------
# 11. 原有独占行格式（标题单独占一行，无粘连）结果不变
# ---------------------------------------------------------------------------

def test_standalone_heading_format_is_unaffected() -> None:
    text = "第一章 开端\n" + "正文内容平铺直叙。" * 40 + "\n第二章 发展\n" + "正文内容继续推进。" * 40
    result = ingest_novel(text.encode("utf-8"))

    assert result["auto_split"] is False
    assert [c["title"] for c in result["chapters"]] == ["第一章 开端", "第二章 发展"]
    assert all(c["content"].startswith(c["title"]) for c in result["chapters"])
