    chapters = ingest_novel(_VOLUME_UNIT_MISMATCH_TEXT.encode("utf-8"))["chapters"]

    assert len(chapters) == 1
    assert chapters[0]["title"] == "第一卷 风起"
    assert "第2章节奏加快" in chapters[0]["content"]


