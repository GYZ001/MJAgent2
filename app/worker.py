"""Compatibility facade for media workers.

真实实现在 :mod:`app.media_exec`（该包 ``__init__.py`` 的模块 docstring 有完整
拆包写法说明）。本模块曾经把 ``media_exec/*.py`` 五个切片源码第二次 ``exec()``
进自己的 ``globals()``，那会产生每个类/函数/可变注册表的第二份互不相识的拷
贝——``LeaseLost``/``VideoPlanStaleFence``/``ReviewDependencyFence``/
``VideoInputRepairRequired``/``ProviderCreateUnresolved``/
``VideoInflightAdmissionDeferred`` 从 ``app.media_exec`` 副本抛出时，不是
``app.worker`` 副本类的实例，``except worker.LeaseLost`` 抓不住，一路穿透到顶
层被当成未知故障。之后曾经改成把本模块整体注册成 ``app.media_exec`` 在
``sys.modules`` 里的别名（同一个模块对象），解决了两份拷贝的问题，但代价是
``app.media_exec`` 本身也还是 exec() 外观（真正的架构债务）。

``app.media_exec`` 已经拆成真包：``common``/``enqueue``/``legacy_keyframes``/
``run_job``/``concat`` 是五个独立模块，互相需要的名字用显式 sibling import。
本模块现在做的是显式再导出——不是整体别名，而是把 ``app.media_exec.__all__``
里的每一个名字（含下划线私有名）原样导入到这里，保持全仓 ``import
app.worker``、``from app import worker``、``worker.xxx`` 属性访问、
``monkeypatch.setattr(worker, "xxx", stub)`` 调用点不用改一行。名字来自
``app.media_exec`` 的同一个对象（函数/类/共享可变注册表全部如此，因为 Python
的具名 import 绑定的是同一个对象引用，不是拷贝）——``LeaseLost`` 等围栏异常与
``_workers`` 等注册表在 ``app.worker``、``app.media_exec`` 包本身、以及实际
定义/读写它们的子模块（如 ``app.media_exec.run_job``）之间仍然是同一份。

唯一的例外是 ``__path__``：``app.media_exec`` 是真正的包（有 ``__path__``），
本模块是普通 ``.py`` 文件（没有）——这是 Python 模块与包与生俱来的差异，不是
本次拆包引入的能力缺口，全仓没有代码读取 ``worker.__path__``。

测试打桩见 ``tests/conftest.py`` 的 ``patch_worker_everywhere(monkeypatch,
name, value)`` 与 ``tests/test_worker_monkeypatch_guard.py``：真包拆分后，
``monkeypatch.setattr(worker, "name", stub)`` 只改本模块自己的 re-export 属
性，改不到真正调用该名字的 ``app.media_exec`` 子模块，必须用
``patch_worker_everywhere`` 才能打到全部。
"""
