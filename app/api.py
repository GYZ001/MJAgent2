"""REST API compatibility facade.

The real implementation lives in :mod:`app.domain` (see that package's
``__init__`` docstring for the full history of why this module used to
``exec()`` the same ``domain/*.py`` source files a *second* time into its
own ``globals()``, and why a later revision made it a bare ``sys.modules``
alias of ``app.domain`` instead).

This module is neither of those anymore. ``app.domain`` is now a real
multi-file package (P0-1): each chunk (``common``/``projects``/``bible_ops``/
``screenplay_ops``/``storyboard_ops``/``review_wall``/``video_ops``) is its
own module, imported by the normal Python import machinery. A bare
``sys.modules[__name__] = app.domain`` alias trick still happens to work at
runtime for plain ``import app.api`` / ``from app import api`` (both end up
pointing at the same ``app.domain`` module object), but it does not survive
``import app.api.storyboard_ops``-style dotted submodule access reliably
across every Python import-machinery code path, and -- more importantly --
it is a second undocumented mechanism doing the same job this module's own
explicit import list already does more legibly. So instead, this module
plainly re-exports, by name, every symbol ``app.domain`` exposes (which is
in turn every symbol every domain chunk used to expose through the old
shared ``exec()`` namespace -- see ``app/domain/__init__.py``'s docstring
for how that full list was produced and verified against a pre-refactor
snapshot, not hand-typed).

Because this is a real import list (not an alias), ``app.api.<name>`` and
``app.domain.<name>`` are *different* bindings that happen to start out
pointing at the same object -- ``monkeypatch.setattr(api, "name", stub)``
only rebinds this module's own copy, not ``app.domain``'s re-export or any
of the seven chunk-local copies real call sites actually resolve ``name``
through. Use ``tests.conftest.patch_api_everywhere(monkeypatch, name,
value)`` instead (enforced by ``tests/test_api_monkeypatch_guard.py``'s AST
guard) rather than patching ``api``/``app.domain`` directly.

``router``, ``_project_video_queue_pause_requests`` and every other
domain-owned mutable object remain single-instance: this module imports them
by reference (``from app.domain import router``), which binds the identical
object every domain chunk itself imported from ``app.domain.common`` /
``app.domain.video_ops`` -- there is exactly one ``APIRouter`` and exactly
one pause-request set behind every access path, same as before.

See docs/architecture_layering_plan_2026-08-29.md (P0-1) and
docs/coupling_review_2026-08-29.md (C1) for the full writeup.
"""
