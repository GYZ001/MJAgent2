"""分镜段草稿的确定性校验：画面里不得出现叠加式文字（浮现文字/文字标识/标题条/名条/字幕）。

产品规则（2026-09-14 用户拍板）：视频只负责画面与声音，字幕由后期功能另做；画面本身需要的
文字（牌匾、书信、招牌、屏幕内容）必须附着在场景物体上。2026-09-15《龙猫出爪》第 1 集第 2 镜：
原文有一行「【后期字幕】距续约 30 天」（后期指令），分镜模型写成「画面右下角浮现白色“距续约
30天”的文字标识」，视频模型照画，字幕闸门照拦，自动重提到第 3 版全被拦，白花三次生成费。
方言规则只在提示词里，这里把它做成闸门：命中就报错让模型重写（不做机械改写——载体该是
手机屏幕还是横幅，由模型按原文决定），报错文案写清合法写法。
"""
from __future__ import annotations

import re
from typing import Any

# 叠加式呈现的措辞（闭集语法形态，不是内容名单）。「不出字幕 / 不叠加字幕 / 无字幕 / 无水印」是
# 约束句里的否定形式，不算违规。
_OVERLAY_RE = re.compile(
    r"浮现[^，。；\n]{0,12}(?:文字|字样|字幕|标识|标题)"
    r"|(?:文字|字样)标识"
    r"|标题条|名条|说话人名"
    r"|【后期字幕】|后期字幕"
    r"|(?:左|右)?(?:上|下)角[^，。；\n]{0,10}(?:文字|字样|字幕)"
    r"|(?<!不出)(?<!不叠加)(?<!无)(?<!不加)(?<!不带)字幕"
)


def overlay_text_errors(draft: Any) -> list[str]:
    """prompt_text 里出现叠加式文字措辞即报错；返回空列表表示通过。"""
    prompt = str(getattr(draft, "prompt_text", "") or "")
    hits = sorted({m.group(0) for m in _OVERLAY_RE.finditer(prompt)})
    if not hits:
        return []
    return [
        "画面里不得出现叠加式文字（" + "、".join(f"「{h}」" for h in hits[:4]) + "）："
        "台词只以声音呈现，字幕、标题条、名条由后期功能另做；原文里的【后期字幕】是后期指令，"
        "不写进画面。画面确实需要的文字必须附着在场景物体上并写清载体与逐字内容"
        "（如「手机屏幕上显示『距续约 30 天』」「横幅上『开业大吉』四字」），不写「画面某角浮现文字」。"
    ]


__all__ = ["overlay_text_errors"]
