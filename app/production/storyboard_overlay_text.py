"""分镜段草稿的确定性校验：画面里不得出现台词字幕 / 说话人名条（把台词文本叠在画面上）。

产品规则（2026-09-14 用户拍板，2026-09-15 收窄）：视频只负责画面与声音，字幕由后期功能另做。
拦的只有一类：把台词/字幕/说话人名条叠在画面上。「不出字幕」「无字幕」这类约束句的否定
形式不算。命中就报错让模型重写，不做机械改写。

2026-09-28 更新：``app.production.storyboard_dialects`` 的默认方言规则已从「画面本身需要的
文字（牌匾、书信、屏幕内容）由视频模型直接生成」改为「画面不出现需要阅读的文字」（该模型中文
字形不稳定，见该模块 docstring 的同日改动）；本文件判据本身不变——依旧只拦「把台词叠在画面
上」这一类，不新增对牌匾/屏幕类文字的黑名单式拦截，模型若仍写出这类文字不会被本校验器拦下，
是方言层的默认建议变了，不是这里新增了强约束。``overlay_text_errors`` 返回给模型重写的提示语
同步改写：旧提示语里「画面本身需要的文字……可以写，写清载体与逐字内容即可」与新默认正面冲突，
命中重试时会重新诱导模型把牌匾/屏幕文字逐字画出来，已替换成与新默认一致的表述。
"""
from __future__ import annotations

import re
from typing import Any

_SUBTITLE_RE = re.compile(
    r"(?<!不出)(?<!不叠加)(?<!无)(?<!不加)(?<!不带)(?<!不显示)字幕"
    r"|名条|说话人名|台词文本|台词字样|对白文字"
)


def overlay_text_errors(draft: Any) -> list[str]:
    """prompt_text 里出现「把台词叠在画面上」的措辞即报错；返回空列表表示通过。"""
    prompt = str(getattr(draft, "prompt_text", "") or "")
    hits = sorted({m.group(0) for m in _SUBTITLE_RE.finditer(prompt)})
    if not hits:
        return []
    return [
        "画面里不得出现台词字幕或说话人名条（" + "、".join(f"「{h}」" for h in hits[:4]) + "）："
        "台词只以声音呈现，字幕由后期功能另做；画面里也不出现需要阅读的文字，带屏幕的物体改从"
        "背面、侧面或虚焦角度拍摄，招牌、黑板、书信这类背景物体只写材质与外形，具体文字信息改由"
        "台词或画外音说出。"
    ]


__all__ = ["overlay_text_errors"]
