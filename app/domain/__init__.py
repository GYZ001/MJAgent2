"""Domain modules split out of :mod:`app.api`.

This package is the single canonical namespace for the whole domain-API
subsystem, and a real Python package: each of the seven chunk files below
(``common``/``projects``/``bible_ops``/``screenplay_ops``/``storyboard_ops``/
``review_wall``/``video_ops``) is its own module, executed exactly once by
the normal Python import machinery the first time anything imports it --
there is no source-injection re-execution into a shared namespace anymore
(see ``git log`` for the previous ``exec`` + ``compile`` loop this file used
to run, and ``app/api.py``'s docstring for why that broke monkeypatching).

Every chunk imports the specific names it needs from its sibling chunks
explicitly (``from app.domain.common import router`` and so on) instead of
relying on a shared globals() dict. ``storyboard_ops`` <-> ``video_ops`` and
``storyboard_ops`` <-> ``review_wall`` are genuinely bidirectional at the
call-graph level (each side calls into the other), which a straight-line
package of real modules cannot express as *two* top-level ``import``
statements without a circular-import error -- ``storyboard_ops.py`` resolves
its side of both cycles with a handful of deferred (in-function) imports
instead (see the comment above ``_shot_contract_json`` in that file). Every
other cross-chunk dependency is a plain top-level import.

This ``__init__.py`` re-exports, by name, every symbol every chunk used to
expose through the old shared namespace -- including the seven chunk names
themselves (``common``, ``projects``, etc., which become real attributes of
this package automatically the moment any ``from .chunk import x`` statement
below imports them; see any Python reference on submodule/parent-package
binding). ``__all__`` is the exact union of all seven chunks' own
``__all__ = [name for name in globals() if not name.startswith("__")]``
lists (each chunk file still ends with that line, now capturing that
module's own real globals -- its own definitions plus whatever it
imported -- instead of a namespace shared with six other files). Nothing
that used to be reachable as ``app.domain.<name>`` (or, transitively,
``app.api.<name>``; see ``app/api.py``) was dropped: this list was generated
by importing the finished package and diffing ``dir()`` against a snapshot
taken before this refactor (P0-1), not hand-typed, specifically to make that
kind of silent loss impossible.

Because every chunk now holds its *own* copy of any name it imports from a
sibling (normal Python import semantics: ``from x import y`` binds a new
name in the importing module, it does not alias the attribute lookup),
``monkeypatch.setattr(api, "name", stub)`` only reaches ``app.api``'s and
``app.domain``'s own re-export copies, not the seven chunk-local copies the
real call sites resolve ``name`` through. Use
``tests.conftest.patch_api_everywhere(monkeypatch, name, value)`` instead --
see ``tests/test_api_monkeypatch_guard.py`` for the AST guard that enforces
this everywhere under ``tests/``.

See docs/architecture_layering_plan_2026-08-29.md (P0-1) and
docs/coupling_review_2026-08-29.md (C1) for the full writeup.
"""
